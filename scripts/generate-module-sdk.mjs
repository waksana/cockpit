import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const repository = fileURLToPath(new URL('..', import.meta.url));
const output = resolve(repository, 'packages/module-api/src/wire.ts');

export function generateModuleSdk(root = repository) {
  const projection = resolve(root, 'packages/protocol/src/module-sdk-projection.ts');
  const configFile = ts.readConfigFile(resolve(root, 'packages/protocol/tsconfig.json'), ts.sys.readFile);
  assert.equal(configFile.error, undefined, 'Cannot read protocol TypeScript configuration');
  const config = ts.parseJsonConfigFileContent(configFile.config, ts.sys, resolve(root, 'packages/protocol'));
  const program = ts.createProgram([projection], {
    ...config.options,
    noEmit: true,
    paths: { '@waksana/cockpit-module-sdk': [resolve(root, 'packages/module-api/src/contract.ts')] },
  });
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(projection);
  assert.ok(source, 'SDK projection source is missing');
  const diagnostics = program.getSemanticDiagnostics(source);
  assert.equal(diagnostics.length, 0, ts.formatDiagnostics(diagnostics, {
    getCanonicalFileName: name => name, getCurrentDirectory: () => root, getNewLine: () => '\n',
  }));
  const symbols = checker.getExportsOfModule(checker.getSymbolAtLocation(source));
  const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
  const declarations = symbols.sort((left, right) => left.name.localeCompare(right.name, 'en')).map(symbol => {
    const type = checker.getDeclaredTypeOfSymbol(symbol);
    const text = checker.typeToString(type, source, ts.TypeFormatFlags.NoTruncation
      | ts.TypeFormatFlags.InTypeAlias | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope);
    return `export type ${symbol.name} = ${text};\n`;
  }).join('\n');
  const parsed = ts.createSourceFile('wire.ts', declarations, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  assert.equal(parsed.parseDiagnostics.length, 0, 'SDK projection is not valid TypeScript');
  const names = new Set([...symbols.map(symbol => symbol.name), 'ModuleEventPayload', 'Record', 'Array', 'ReadonlyArray']);
  const text = node => printer.printNode(ts.EmitHint.Unspecified, node, parsed);
  const sorted = nodes => [...nodes].sort((left, right) => text(left).localeCompare(text(right), 'en'));
  const transformed = ts.transform(parsed, [context => {
    const visit = node => {
      assert.ok(node.kind !== ts.SyntaxKind.AnyKeyword && !ts.isImportTypeNode(node),
        'SDK projection contains an unresolved or internal type');
      if (ts.isTypeReferenceNode(node)) {
        assert.ok(ts.isIdentifier(node.typeName) && names.has(node.typeName.text),
          `SDK projection has an unexported reference: ${text(node)}`);
      }
      const result = ts.visitEachChild(node, visit, context);
      // Schema inference order is not an API change. Keep generated output stable.
      if (ts.isUnionTypeNode(result)) return context.factory.updateUnionTypeNode(result, sorted(result.types));
      if (ts.isTypeLiteralNode(result)) return context.factory.updateTypeLiteralNode(result, sorted(result.members));
      return result;
    };
    return source => ts.visitNode(source, visit);
  }]);
  const body = printer.printFile(transformed.transformed[0]);
  transformed.dispose();
  return '// Generated by scripts/generate-module-sdk.mjs. Edit the protocol schemas, not this file.\n'
    + "import type { ModuleEventPayload } from './contract.ts';\n\n"
    + body;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [mode, ...extra] = process.argv.slice(2);
  assert.ok(extra.length === 0 && (mode === '--check' || mode === '--write'),
    'Usage: generate-module-sdk.mjs --check | --write');
  const generated = generateModuleSdk();
  if (mode === '--write') writeFileSync(output, generated);
  else assert.equal(readFileSync(output, 'utf8'), generated, 'SDK projection is stale; run pnpm sdk:generate');
}
